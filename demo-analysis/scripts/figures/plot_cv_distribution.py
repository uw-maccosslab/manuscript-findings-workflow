"""Render the QC per-protein CV distribution for the delivered proteomics matrix.

A publication-ready figure (dual-exported SVG + 300 DPI PNG, plus a separate swatch
legend image) showing the per-feature coefficient of variation (``CV = std / mean``
across the 40 experimental samples) of the delivered plasma-proteomics protein matrix,
drawn as a translucent histogram + Gaussian-KDE curve with the median CV marked.

**Single processing state — NOT a normalization overlay.** The canonical CV figure
overlays raw -> normalized -> batch-corrected states to show whether processing
tightened the technical spread. This project has only ONE delivered processing state:
``data/protein-data.csv`` arrives already log2, already median-normalized, and already
batch-corrected on ``Cohort`` (finding 0004); the pre-processing matrices were never
delivered (``results/qc_states/README.md``). So the state series collapses to a single
curve here, and this script renders exactly one CV distribution. It fabricates no
raw/normalized overlay curves. Controls are absent (finding 0003), so there is no
per-control-type CV figure either.

**Why the linear state.** CV (``std / mean``) is only defined on a positive linear
scale — on log2 the per-feature mean sits near 0 so the ratio explodes, and the CV
template (:mod:`common.cv`) hard-refuses a non-linear ``Dataset`` with
``CVScaleError``. This script therefore loads ``results/qc_states/delivered_linear/``,
the ``to_linear`` (``2**log2``) de-logged IMAGE of the already-normalized,
batch-corrected delivered matrix — NOT raw intensity — so the CV computation is
well-defined. Feeding ``delivered_log/`` here would (correctly) raise ``CVScaleError``.

Input (read-only, regenerated by ``scripts/scratch/qc_prep.py``):
  results/qc_states/delivered_linear/   linear-scale delivered Dataset (40 x 2340)
  state/color_registry.json             NormalizationState category -> color map

Run:  ./.venv/bin/python scripts/figures/plot_cv_distribution.py
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import numpy as np

# `common.*` lives at scripts/common/ -- make `scripts/` importable regardless of how
# this file is invoked, matching scripts/figures/plot_group_x_cohort_confound.py.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.cv import plot_cv_distribution
from common.dataset_io import load_dataset
from common.figure_io import save_figure

LOGGER = logging.getLogger("plot_cv_distribution")

DEFAULT_STATE_DIR = Path("results") / "qc_states" / "delivered_linear"
DEFAULT_OUTPUT_DIR = Path("figures") / "qc" / "cv"
DEFAULT_BASE_NAME = "cv-delivered-linear"
DEFAULT_REGISTRY = Path("state") / "color_registry.json"

# The single available processing state. This label is the color-registry value under
# the "NormalizationState" category, so it keeps its color in any later CV figure.
STATE_LABEL = "Delivered (normalized, batch-corrected)"

# Short title (names the comparison + the state). The load-bearing caveat is a smaller,
# separate note beneath it -- a mandatory marker so the single-state premise reads off
# the canvas, per the figure spec.
TITLE = "Per-protein CV — delivered plasma proteomics matrix"
CAVEAT = (
    "delivered (normalized, batch-corrected) matrix, de-logged to linear for CV; "
    "single available state (finding 0004);\n"
    "CV is not a pre/post-normalization comparison here"
)


def data_version(state_dir: Path) -> str:
    """Short content hash of the linear-state abundance matrix, for provenance."""
    return hashlib.sha256((state_dir / "abundances.npy").read_bytes()).hexdigest()[:16]


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(name)s: %(message)s")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--state-dir", type=Path, default=DEFAULT_STATE_DIR)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--base-name", type=str, default=DEFAULT_BASE_NAME)
    parser.add_argument("--registry", type=Path, default=DEFAULT_REGISTRY)
    args = parser.parse_args()

    dv = data_version(args.state_dir)
    LOGGER.info("data_version(abundances.npy)=%s", dv)

    dataset = load_dataset(args.state_dir)
    LOGGER.info(
        "loaded %s: %d sample(s) x %d feature(s), scale=%s",
        args.state_dir,
        *dataset.abundances.shape,
        dataset.scale,
    )

    # Single-state render: one labelled linear Dataset -> one CV distribution. The
    # template raises CVScaleError on a non-linear Dataset (as delivered_log would be).
    plot = plot_cv_distribution(
        {STATE_LABEL: dataset},
        category="NormalizationState",
        feature_type="protein",
        title=None,  # title/caveat added below so the caveat can be a smaller note
        legend_title="Processing state",
        registry_path=args.registry,
        persist_colors=True,
    )

    # Distribution shape summary (finite per-feature CVs), logged for the finding.
    cvs = plot.result.cvs[STATE_LABEL]
    finite = cvs[np.isfinite(cvs)]
    median = plot.result.medians[STATE_LABEL]
    q25, q75 = (float(v) for v in np.percentile(finite, [25, 75]))
    p95, p99 = (float(v) for v in np.percentile(finite, [95, 99]))
    LOGGER.info(
        "per-protein CV: n_finite=%d (of %d), median=%.4f, IQR=[%.4f, %.4f], "
        "p95=%.4f, p99=%.4f, min=%.4f, max=%.4f, frac>0.20=%.3f, frac>0.50=%.3f",
        finite.size,
        cvs.size,
        median,
        q25,
        q75,
        p95,
        p99,
        float(finite.min()),
        float(finite.max()),
        float(np.mean(finite > 0.20)),
        float(np.mean(finite > 0.50)),
    )
    LOGGER.info("color_map=%s", plot.color_map)

    # Short bold title + a smaller italic caveat note (the mandatory single-state
    # marker). Headroom is reserved so neither overlaps the axes.
    fig = plot.figure
    fig.subplots_adjust(top=0.80)
    fig.suptitle(TITLE, y=0.99, fontsize=14, weight="bold")
    fig.text(
        0.5,
        0.885,
        CAVEAT,
        ha="center",
        va="top",
        fontsize=9,
        color="#444444",
        style="italic",
    )

    artifacts = save_figure(
        fig, args.output_dir, args.base_name, legend_fig=plot.legend_figure
    )
    LOGGER.info("wrote %s", artifacts.svg)
    LOGGER.info("wrote %s", artifacts.png)
    LOGGER.info("wrote %s", artifacts.legend_svg)
    LOGGER.info("wrote %s", artifacts.legend_png)


if __name__ == "__main__":
    main()
